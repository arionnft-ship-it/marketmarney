'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const live=require('./xau-public-live.cjs');
const now=1762660800000;
const privateStatus={state:'live',ageMs:12,serverTime:now,quote:{symbol:'XAU/USD',price:4100.25,bid:4100.25,ask:4100.55,timestamp:now,brokerSymbol:'XAUUSD.a',brokerServer:'FBS-Real-5',brokerServerTime:1762660799},dailySession:{id:'private-session',symbol:'XAU/USD',timeframe:'1day',mode:'live',provider:'private',timezone:'UTC',opensAt:1762646400000,closesAt:1762732800000,serverTime:now,confirmedClosed:false}};
const publicStatus=live.sanitizeRelayStatus(privateStatus,now);
assert.equal(publicStatus.state,'live');
assert.deepEqual(Object.keys(publicStatus.quote).sort(),['ask','bid','mode','price','provider','sessionId','symbol','timestamp','timestampBasis'].sort());
assert.equal(publicStatus.quote.brokerServer,undefined);
assert.equal(publicStatus.quote.brokerSymbol,undefined);
assert.equal(publicStatus.quote.provider,live.PROVIDER);
assert.equal(publicStatus.session.provider,live.PROVIDER);
assert.equal(live.sanitizeRelayStatus({...privateStatus,state:'stale',quote:null},now).state,'stale');
const html='<html><head><title>x</title></head><body>LIVE · 30 DETIK GOLD API · SPOT Mode LIVE memakai harga spot Gold API setiap sekitar 30 detik.</body></html>';
const enhanced=live.enhancePublicPage(html);
assert.match(enhanced,/data-warxau-public-live/);
assert.match(enhanced,/LIVE · STREAM/);
assert.match(enhanced,/LIVE STREAM · BID/);
assert.equal(live.enhancePublicPage(enhanced),enhanced);
new vm.Script(live.CLIENT);
assert.match(live.CLIENT,/new EventSource\(BASE\+'\/stream'\)/);
assert.match(live.CLIENT,/Object\.defineProperty\(root,'MMGold'/);
assert.doesNotMatch(live.CLIENT,/Math\.random|interpolat/i);
const fakeRelay={status:()=>privateStatus};
const server=live.createPublicXauLive({relay:fakeRelay,clock:()=>now});
assert.equal(server.owns({url:live.BASE+'/stream'}),true);
assert.equal(server.owns({url:live.ASSET}),true);
assert.equal(server.current().quote.bid,4100.25);
assert.equal(typeof server.wrapPage,'function');
server.close();
console.log(JSON.stringify({ok:true,version:live.VERSION,provider:live.PROVIDER}));
